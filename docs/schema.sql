-- 재고 관리 스키마 (PostgreSQL)
-- 마이그레이션(src/main/resources/db/migration)을 모두 실행한 뒤의 현재 스키마 전체다.
-- 스키마를 바꾸면 새 마이그레이션 파일을 더하고 이 파일도 같이 고친다.

CREATE TABLE product
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku        VARCHAR(50)  NOT NULL,
    name       VARCHAR(100) NOT NULL,
    quantity   INTEGER      NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) NOT NULL DEFAULT now(),
    updated_at TIMESTAMP(6) NOT NULL DEFAULT now(),
    CONSTRAINT uk_product_sku UNIQUE (sku),
    CONSTRAINT ck_product_quantity CHECK (quantity >= 0)
);

COMMENT ON TABLE product IS '상품';
COMMENT ON COLUMN product.id IS '상품 ID';
COMMENT ON COLUMN product.sku IS 'SKU';
COMMENT ON COLUMN product.name IS '상품명';
COMMENT ON COLUMN product.quantity IS '현재 재고 수량';
COMMENT ON COLUMN product.created_at IS '등록 시각';
COMMENT ON COLUMN product.updated_at IS '수정 시각';

CREATE TABLE product_stock_history
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id      BIGINT       NOT NULL,
    type            VARCHAR(50)  NOT NULL,
    quantity        INTEGER      NOT NULL,
    before_quantity INTEGER      NOT NULL,
    after_quantity  INTEGER      NOT NULL,
    created_at      TIMESTAMP(6) NOT NULL DEFAULT now(),
    CONSTRAINT fk_product_stock_history_product FOREIGN KEY (product_id) REFERENCES product (id),
    CONSTRAINT ck_product_stock_history_quantity CHECK (quantity > 0)
);

CREATE INDEX idx_product_stock_history_product_id ON product_stock_history (product_id, id);

COMMENT ON TABLE product_stock_history IS '재고 변동 이력';
COMMENT ON COLUMN product_stock_history.id IS '재고 변동 이력 ID';
COMMENT ON COLUMN product_stock_history.product_id IS '상품 ID';
COMMENT ON COLUMN product_stock_history.type IS '변동 유형 (INBOUND/OUTBOUND)';
COMMENT ON COLUMN product_stock_history.quantity IS '변동 수량';
COMMENT ON COLUMN product_stock_history.before_quantity IS '변동 전 재고 수량';
COMMENT ON COLUMN product_stock_history.after_quantity IS '변동 후 재고 수량';
COMMENT ON COLUMN product_stock_history.created_at IS '변동 시각';
